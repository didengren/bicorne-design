#!/usr/bin/env node
/**
 * generate.mjs — token.json → tailwind.config.ts
 *
 * Usage:
 *   node generate.mjs --token ./token.json --prefix dash --out ./tailwind.config.ts
 *
 * Reads a token.json conforming to design-token.schema.json, emits a tailwind config
 * that exposes every token as a dash-*-prefixed utility class.
 */

import fs from 'node:fs'
import path from 'node:path'

function parseArgs() {
  const args = process.argv.slice(2)
  const opts = {}
  for (let i = 0; i < args.length; i += 2) {
    const k = args[i].replace(/^--/, '')
    opts[k] = args[i + 1]
  }
  return opts
}

function flatten(obj, prefix = '', sep = '-') {
  // Recursively flatten a nested object into dash-separated keys
  // e.g. { surface: { 1: '#0f1219' } } → { 'surface-1': '#0f1219' }
  const out = {}
  for (const [k, v] of Object.entries(obj)) {
    const key = prefix ? `${prefix}${sep}${k}` : k
    if (v && typeof v === 'object' && !Array.isArray(v) && !('value' in v)) {
      Object.assign(out, flatten(v, key, sep))
    } else if (v && typeof v === 'object' && 'value' in v) {
      // W3C design token format: { value: ..., type: ... }
      out[key] = v.value
    } else {
      out[key] = v
    }
  }
  return out
}

function toPx(v) {
  if (typeof v === 'number') return `${v}px`
  if (typeof v === 'string') return /^\d+$/.test(v) ? `${v}px` : v
  return v
}

function generateColors(colors, prefix) {
  if (!colors) return null
  const flat = flatten(colors)
  const lines = []
  for (const [k, v] of Object.entries(flat)) {
    lines.push(`        '${prefix}-${k}': '${v}',`)
  }
  return `{\n${lines.join('\n')}\n      }`
}

function generateSpacing(spacing, prefix) {
  if (!spacing) return null
  const lines = []
  for (const [k, v] of Object.entries(spacing)) {
    lines.push(`        '${prefix}-${k}': '${toPx(v)}',`)
  }
  return `{\n${lines.join('\n')}\n      }`
}

function generateBorderRadius(radii, prefix) {
  if (!radii) return null
  const lines = []
  for (const [k, v] of Object.entries(radii)) {
    lines.push(`        '${prefix}-${k}': '${toPx(v)}',`)
  }
  return `{\n${lines.join('\n')}\n      }`
}

function generateBoxShadow(shadows, prefix) {
  if (!shadows) return null
  const lines = []
  for (const [k, v] of Object.entries(shadows)) {
    lines.push(`        '${prefix}-${k}': '${v}',`)
  }
  return `{\n${lines.join('\n')}\n      }`
}

function generateFontFamily(families, prefix) {
  if (!families) return null
  const lines = []
  for (const [k, v] of Object.entries(families)) {
    const stack = typeof v === 'string' ? v : v.stack || v
    lines.push(`        '${prefix}-${k}': ['${stack.replace(/'/g, "\\'")}'],`)
  }
  return `{\n${lines.join('\n')}\n      }`
}

function generateAnimations(animations, keyframes, prefix) {
  if (!animations) return null
  const animLines = []
  const kfLines = []
  for (const [k, cfg] of Object.entries(animations)) {
    const dur = cfg.duration || '600ms'
    const ease = cfg.easing || 'ease'
    const fill = cfg.fillMode || 'both'
    animLines.push(`        '${prefix}-${k}': '${prefix}-${k} ${dur} ${ease} ${fill}',`)
  }
  for (const [k, frames] of Object.entries(keyframes || {})) {
    if (!animations[k]) continue
    const stops = []
    for (const [stop, props] of Object.entries(frames)) {
      const propLines = []
      for (const [pk, pv] of Object.entries(props)) {
        // CSS prop key: "stroke-dashoffset" or "backgroundPosition"
        const cssKey = pk.replace(/[A-Z]/g, m => `-${m.toLowerCase()}`)
        propLines.push(`          ${cssKey}: '${pv}',`)
      }
      stops.push(`        '${stop}': {\n${propLines.join('\n')}\n        },`)
    }
    kfLines.push(`      '${prefix}-${k}': {\n${stops.join('\n')}\n      },`)
  }
  return {
    keyframes: kfLines.length ? `{\n${kfLines.join('\n')}\n    }` : null,
    animation: animLines.length ? `{\n${animLines.join('\n')}\n      }` : null,
  }
}

function generate(token, prefix) {
  const c = generateColors(token.colors, prefix)
  const s = generateSpacing(token.spacing, prefix)
  const r = generateBorderRadius(token.borderRadius, prefix)
  const sh = generateBoxShadow(token.shadows, prefix)
  const f = generateFontFamily(token.fontFamilies || token.typography?.families, prefix)
  const a = generateAnimations(token.animations, token.keyframes, prefix)

  const extend = []
  if (c) extend.push(`      colors: ${c},`)
  if (s) extend.push(`      spacing: ${s},`)
  if (r) extend.push(`      borderRadius: ${r},`)
  if (sh) extend.push(`      boxShadow: ${sh},`)
  if (f) extend.push(`      fontFamily: ${f},`)
  if (a?.keyframes) extend.push(`      keyframes: ${a.keyframes},`)
  if (a?.animation) extend.push(`      animation: ${a.animation},`)

  return `import type { Config } from 'tailwindcss'

/**
 * AUTO-GENERATED by bicorne-design/tailwind-bridge/generate.mjs
 * Do not edit by hand — re-run the generator to update.
 * Source: token.json
 * Generated: ${new Date().toISOString()}
 */
export default {
  content: ['./index.html', './src/**/*.{vue,ts,tsx,js,jsx}'],
  theme: {
    extend: {
${extend.join('\n')}
    },
  },
} satisfies Config
`
}

const opts = parseArgs()
if (!opts.token || !opts.out) {
  console.error('Usage: generate.mjs --token <path> --out <path> [--prefix dash]')
  process.exit(1)
}

const token = JSON.parse(fs.readFileSync(path.resolve(opts.token), 'utf-8'))
const prefix = opts.prefix || 'dash'
const out = generate(token, prefix)
fs.writeFileSync(path.resolve(opts.out), out, 'utf-8')
console.log(`✓ Generated ${opts.out} from ${opts.token} (prefix: ${prefix})`)
